import pandas as pd
import numpy as np
import seaborn as sns

#importing dataset
banknote_df = pd.read_csv("https://raw.githubusercontent.com/Sanchitbhadani-1/Dimensionality-Reduction/refs/heads/main/Learning%20PCA%20and%20LDA/banknote(in).csv")
#displaying dataset header
banknote_df.head()

# dividing data into features and labels
X = banknote_df.drop(["class"], axis = 1)
y = banknote_df.filter(["class"], axis = 1)

#dividing data into 80-20% training and test sets
from sklearn.model_selection import train_test_split
X_train, X_test, y_train, y_test = train_test_split(X, y,
test_size=0.20, random_state=0)

#applying scaling on training and test data
from sklearn.preprocessing import StandardScaler
sc = StandardScaler()
X_train = sc.fit_transform(X_train)
X_test = sc.transform(X_test)

#importing PCA class
from sklearn.decomposition import PCA
#creating object of the PCA class
pca = PCA()
#training PCA model on training data
X_train = pca.fit_transform(X_train)
#making predictions on test data
X_test = pca.transform(X_test)

#printing variance ratios
variance_ratios = pca.explained_variance_ratio_
print(variance_ratios)

#use two principal components
