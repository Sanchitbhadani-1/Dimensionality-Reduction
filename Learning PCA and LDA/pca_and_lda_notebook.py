# If you intended to have 2 components, you should specify n_components=2 in the initial PCA call.
pca = PCA(n_components=1) # Changed from 2 to 1 to resolve the ValueError
X_train = pca.fit_transform(X_train)
X_test = pca.transform(X_test)

#making predictions using logistic regression
from sklearn.linear_model import LogisticRegression
#training the logistic regression model
lg = LogisticRegression ( )
lg.fit ( X_train , y_train )
# Predicting the Test set results
y_pred = lg.predict ( X_test )
#evaluating results
from sklearn.metrics import accuracy_score
print ( accuracy_score ( y_test , y_pred ) )
# 0.8666666666666667

